import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import sys
import io
import contextlib
from typing import Dict, Any, Tuple
from autonomous_data_analyse_agent.ml.pipeline import safe_train_test_split
from autonomous_data_analyse_agent.ml.evaluate import run_cross_validation

class LocalExecutionSandbox:
    def __init__(self):
        """Initializes the local execution sandbox."""
        # Define allowed built-ins for safety, plus required libraries for data science.
        self.allowed_globals = {
            'pd': pd,
            'np': np,
            'plt': plt,
            'sns': sns,
            'safe_train_test_split': safe_train_test_split,
            'run_cross_validation': run_cross_validation,
            '__builtins__': __builtins__
        }
        # In a full production environment, you might restrict __builtins__ further
        # or use a dedicated Docker container for true isolation.

    def execute_code(self, df: pd.DataFrame, code_string: str) -> Tuple[pd.DataFrame, str, bool]:
        """
        Executes dynamically generated Python code on the dataframe.
        
        Args:
            df: The current pandas DataFrame.
            code_string: The python code generated by the LLM.
            
        Returns:
            Tuple containing:
            - The modified DataFrame
            - The captured stdout (print statements) or traceback error string
            - Boolean indicating success (True) or failure (False)
        """
        # Create a fresh local environment with the dataframe
        local_env = {'df': df.copy()}
        
        # Capture standard output and errors
        stdout_capture = io.StringIO()
        
        success = False
        output = ""
        
        try:
            with contextlib.redirect_stdout(stdout_capture):
                with contextlib.redirect_stderr(stdout_capture):
                    # Execute the code in the restricted globals and local env
                    exec(code_string, self.allowed_globals, local_env)
            
            # If execution succeeds, update the output
            output = stdout_capture.getvalue()
            success = True
            
            # The LLM is instructed to modify 'df' in place or reassign 'df' in local_env
            if 'df' in local_env and isinstance(local_env['df'], pd.DataFrame):
                df = local_env['df']
                
        except Exception as e:
            # If the code fails, capture the exception traceback to feed back to the LLM
            import traceback
            output = stdout_capture.getvalue() + "\n" + traceback.format_exc()
            success = False
            
        return df, output, success
